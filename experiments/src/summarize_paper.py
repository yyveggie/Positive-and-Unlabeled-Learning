from __future__ import annotations

import os
import pandas as pd

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(HERE, "results")
COLS = ["breast", "spambase", "mushroom", "adult", "bank"]


def pick(df):
    key = ["dataset", "c", "seed", "method"]
    return df.loc[df.groupby(key)["crit_leeliu"].idxmax()]


grid = pd.concat([pd.read_csv(os.path.join(R, f))
                  for f in ["p1_results.csv", "p15_results.csv", "ext_results.csv"]],
                 ignore_index=True)
grid = grid[~grid.method.isin(["tice_nnpu"])]
off = pick(pd.read_csv(os.path.join(R, "officialgrid_results.csv")))
tab = pd.concat([pick(grid), off[off.phase == "tab"]], ignore_index=True)


mn = pd.concat([pick(pd.read_csv(os.path.join(R, "mnist_results.csv"))),
                off[off.phase == "mnist"]], ignore_index=True)

t = tab.pivot_table(index="method", columns="dataset", values="bacc", aggfunc="mean")[COLS]
t["MEAN"] = t.mean(axis=1)
t["MNIST"] = mn.groupby("method")["bacc"].mean()

CORE = ["vpu", "distpu"]


def grid_desc(df):
    cs = ",".join(f"{c:g}" for c in sorted(df.c.unique()))
    return "c in {%s} x %d seeds" % (cs, df.seed.nunique())


print("=" * 78)
print("PAPER TABLE  test balanced accuracy, PU-only model selection")
print(f"(tabular: mean over {grid_desc(tab)}; MNIST: {grid_desc(mn)})\n")
print("-- ranked methods (official implementations for VPU / Dist-PU) --")
print(t.drop(index=[m for m in CORE if m in t.index])
       .round(3).sort_values("MEAN", ascending=False).to_string())
print("\n-- core reimplementations, fidelity contrast only --")
print(t.loc[[m for m in CORE if m in t.index]].round(3).to_string())


blocks = tab[~tab.method.isin(CORE)].pivot_table(
    index="dataset", columns="method", values="bacc", aggfunc="mean").dropna()
ranks = blocks.rank(axis=1, ascending=False)
print("\naverage dataset rank (lower = better), n_datasets={}, k={}:".format(
    *blocks.shape))
print(ranks.mean().round(2).sort_values().to_string())
print("\nInferential results are generated by hierarchical_reanalysis.py; "
      "dataset-c-seed cells are repeated measurements, not independent blocks.")

print("\nlabel-frequency breakdown (tabular bacc):")
print(tab.pivot_table(index="method", columns="c", values="bacc",
                      aggfunc="mean").round(3).to_string())

print("\nofficial vs core (fidelity gap, tabular MEAN / MNIST):")
for base, offk in [("vpu", "vpu_off"), ("distpu", "distpu_off")]:
    if base in t.index and offk in t.index:
        print(f"  {base:7s} core {t.loc[base,'MEAN']:.3f} / {t.loc[base,'MNIST']:.3f}"
              f"   official {t.loc[offk,'MEAN']:.3f} / {t.loc[offk,'MNIST']:.3f}"
              f"   delta {t.loc[offk,'MEAN']-t.loc[base,'MEAN']:+.3f} /"
              f" {t.loc[offk,'MNIST']-t.loc[base,'MNIST']:+.3f}")
