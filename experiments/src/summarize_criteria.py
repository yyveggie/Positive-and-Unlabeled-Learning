from __future__ import annotations

import os
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = pd.read_csv(os.path.join(HERE, "results", "crit_results.csv"))
KEY = ["dataset", "c", "seed", "method"]
CRITS = ["crit_leeliu", "crit_puauc", "crit_nnpurisk", "crit_f1hat",
         "crit_nnpurisk_true", "crit_f1hat_true"]
NICE = {"crit_leeliu": "Lee-Liu", "crit_puauc": "PU-AUC",
        "crit_nnpurisk": "nnPU risk (est. prior)",
        "crit_f1hat": "estimated F1 (est. prior)",
        "crit_nnpurisk_true": "nnPU risk (true prior)",
        "crit_f1hat_true": "estimated F1 (true prior)",
        "crit_oraclef1": "ORACLE (labeled val)"}
ORDER = ["uasn", "wce", "en", "upu", "nnpu", "imbpu"]

n_cfg = d.groupby(KEY).size()
print(f"{len(d)} runs over {len(n_cfg)} cells, {n_cfg.max()} configurations each\n")


def choose(crit):
    return d.loc[d.groupby(KEY)[crit].idxmax()].set_index(KEY)


def config_of(s):
    return s[["lr", "wd", "hidden", "epoch"]].apply(tuple, axis=1)


oracle = choose("crit_oraclef1")
oracle_cfg = config_of(oracle)
best = d.groupby(KEY)[["f1", "bacc"]].max()
rows = []
for crit in CRITS + ["crit_oraclef1"]:
    s = choose(crit)
    rows.append(dict(criterion=NICE[crit],
                     f1=s.f1.mean(), bacc=s.bacc.mean(),
                     gap_f1=(oracle.f1 - s.f1).mean(),
                     gap_bacc=(oracle.bacc - s.bacc).mean(),
                     regret_f1=(best.f1 - s.f1).mean(),
                     agree=float((config_of(s) == oracle_cfg).mean())))
print("=" * 78)
print(f"A. Cost of each criterion (mean over {d.dataset.nunique()} datasets x "
      f"{d.c.nunique()} c x {d.seed.nunique()} seeds x {d.method.nunique()} methods)")
print("   gap_*   = oracle selection minus this criterion")
print("   regret  = best configuration in the grid minus this criterion")
print("   agree   = fraction of cells where it picks the oracle's configuration\n")
print(pd.DataFrame(rows).set_index("criterion").round(4).to_string())

print("\n" + "=" * 78)
print("B. Test F1 gap to oracle, per method")
tab = {}
for crit in CRITS:
    s = choose(crit)
    tab[NICE[crit]] = (oracle.f1 - s.f1).groupby("method").mean()
print(pd.DataFrame(tab).reindex(ORDER).round(4).to_string())

print("\n" + "=" * 78)
print("C. Stopping epoch each criterion prefers (oracle mean in the last column)")
ep = {NICE[c]: choose(c).groupby("method")["epoch"].mean() for c in CRITS}
ep[NICE["crit_oraclef1"]] = oracle.groupby("method")["epoch"].mean()
print(pd.DataFrame(ep).reindex(ORDER).round(1).to_string())

print("\n" + "=" * 78)
print("D. Does the prior estimate spoil the two criteria that need one?")
a = d.groupby(KEY)[["alpha_true", "alpha_hat"]].first()
a["ratio"] = a.alpha_hat / a.alpha_true
print(a.groupby("dataset")[["alpha_true", "alpha_hat", "ratio"]].mean().round(3).to_string())
def paired(a_crit, b_crit, metric="f1"):
    a, b = choose(a_crit)[metric], choose(b_crit)[metric]
    d_ = (a - b).dropna()
    return d_.mean(), int((d_ > 0).sum()), len(d_)


for est, tru in [("crit_nnpurisk", "crit_nnpurisk_true"),
                 ("crit_f1hat", "crit_f1hat_true")]:
    de = (oracle.f1 - choose(est).f1).mean()
    dt = (oracle.f1 - choose(tru).f1).mean()
    m, wins, n = paired(est, tru)
    print(f"  {NICE[est]:<26s} gap {de:.4f}   with the true prior {dt:.4f}"
          f"   difference {de - dt:+.4f}   (paired: {m:+.4f}, "
          f"wins {wins}/{n})")

print("\n" + "=" * 78)
print("F. Paired tests against Lee-Liu, the criterion the survey used throughout")
for metric in ["f1", "bacc"]:
    print(f"\n{metric}:")
    for crit in CRITS[1:]:
        m, wins, n = paired(crit, "crit_leeliu", metric)
        print(f"  {NICE[crit]:<26s} mean difference {m:+.4f}   "
              f"wins {wins}/{n}")
print("\nCluster-aware bootstrap intervals, exact dataset-level sign-flip tests, "
      "and Holm corrections are generated by hierarchical_reanalysis.py.")
